#!/usr/bin/env python3
"""art_preview: build a quick contact sheet of a gfx/src sheet, palette-resolved and zoomed, at build/art_preview/<name>.png.

  art_preview.py gfx/src/sprite/GFX_BC.png            # or just a name: GFX_BC / LINK / BC
  art_preview.py GFX_BC --zoom 4 --game --used        # as the game shows it (in-game palette rows) + mark tiles the game draws
  art_preview.py LINK --rect 0 0 128 64               # only a rectangle (pixels)
  art_preview.py GFX_C5 --out /tmp/c5.png --no-grid

What you get (one PNG):
  * the sheet at --zoom (default 4x), transparent index 0 as a checkerboard, tile grid every 8 px (--no-grid to hide),
    column numbers across the top and the tile index (hex, = row*16 + col) at the start of every row;
  * with --used, tiles that tools/art/game_map.json says the game really draws get a green corner mark, all others are dimmed
    (--no-dim to keep them bright);
  * with --game, one extra panel per in-game palette variant of that sheet (e.g. GFX_BC: OBJ row 4 = unaware, OBJ row 6 = ALERT),
    because the game does NOT show a sheet with the colours stored in its PNG palette (docs/gfx/art_map.md section 9).
    Without game data for a sheet you just get the PNG-palette panel.
The first panel always uses the PNG's own palette (what you painted with). tools/art/game_map.json is generated by
tools/art/build_game_map.py from emulator dumps; it can be stale if gfx/src/palettes/*.yaml changed.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
MAP = ROOT / "tools" / "art" / "game_map.json"
OUT_DIR = ROOT / "build" / "art_preview"


def find_sheet(arg: str) -> Path:
    p = Path(arg)
    if p.exists():
        return p.resolve()
    name = arg.upper()
    cands = [name, f"GFX_{name}"] if not name.startswith("GFX_") else [name]
    for c in cands:
        hits = sorted((ROOT / "gfx" / "src").rglob(f"{c}.png")) + sorted((ROOT / "gfx" / "src").rglob(f"{arg}.png"))
        if hits:
            return hits[0]
    sys.exit(f"cannot find a sheet for '{arg}' (try a path under gfx/src, a name like GFX_BC, or LINK)")


def hex2rgb(h: str) -> tuple:
    return (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16))


def render(px, size, rect, palette, zoom, grid, used, dim, tile_cols):
    x0, y0, rw, rh = rect
    img = Image.new("RGBA", (rw * zoom, rh * zoom))
    d = ImageDraw.Draw(img)
    # checkerboard behind transparent pixels
    cs = max(4, zoom * 2)
    for yy in range(0, rh * zoom, cs):
        for xx in range(0, rw * zoom, cs):
            c = (58, 58, 66, 255) if ((xx // cs) + (yy // cs)) % 2 == 0 else (44, 44, 50, 255)
            d.rectangle([xx, yy, xx + cs - 1, yy + cs - 1], fill=c)
    for y in range(rh):
        for x in range(rw):
            v = px[x0 + x, y0 + y]
            if v == 0 or v >= len(palette):
                continue
            c = palette[v]
            d.rectangle([x * zoom, y * zoom, (x + 1) * zoom - 1, (y + 1) * zoom - 1], fill=(*c, 255))
    ts = 8 * zoom
    if used is not None:
        for ty in range(rh // 8):
            for tx in range(rw // 8):
                idx = ((y0 // 8) + ty) * tile_cols + (x0 // 8) + tx
                if idx in used:
                    d.polygon([(tx * ts, ty * ts), (tx * ts + 10, ty * ts), (tx * ts, ty * ts + 10)], fill=(60, 220, 90, 255))
                elif dim:
                    d.rectangle([tx * ts, ty * ts, tx * ts + ts - 1, ty * ts + ts - 1], fill=(0, 0, 0, 150))
    if grid:
        for gx in range(0, rw * zoom + 1, ts):
            d.line([(gx, 0), (gx, rh * zoom)], fill=(255, 255, 255, 60))
        for gy in range(0, rh * zoom + 1, ts):
            d.line([(0, gy), (rw * zoom, gy)], fill=(255, 255, 255, 60))
    return img


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("sheet")
    ap.add_argument("--zoom", type=int, default=4)
    ap.add_argument("--rect", nargs=4, type=int, metavar=("X", "Y", "W", "H"))
    ap.add_argument("--game", action="store_true", help="add a panel per in-game palette variant")
    ap.add_argument("--used", action="store_true", help="mark the tiles the game draws (needs tools/art/game_map.json)")
    ap.add_argument("--no-dim", action="store_true")
    ap.add_argument("--no-grid", action="store_true")
    ap.add_argument("--out", type=Path)
    args = ap.parse_args()

    sheet = find_sheet(args.sheet)
    im = Image.open(sheet)
    if im.mode != "P":
        sys.exit(f"{sheet} is not an indexed PNG")
    W, H = im.size
    px = im.load()
    flat = im.getpalette() or []
    png_pal = [tuple(flat[i * 3:i * 3 + 3]) for i in range(len(flat) // 3)]
    rect = tuple(args.rect) if args.rect else (0, 0, W, H)
    name = sheet.stem
    gm = json.loads(MAP.read_text()) if MAP.exists() else None
    info = (gm or {}).get("sheets", {}).get(name)
    used = {int(i) for i in info["used"]} if (args.used and info) else None
    if args.used and not info:
        print(f"note: no game data for {name} in {MAP.relative_to(ROOT)}; --used ignored")
    tile_cols = W // 8
    panels = [("sheet palette (PNG): what you painted with", png_pal)]
    if args.game:
        if info and info["variants"]:
            for v in info["variants"]:
                panels.append((f"in game: {v['label']}", [hex2rgb(c) for c in v["colours"]]))
        else:
            print(f"note: no in-game palette recorded for {name}; showing the PNG palette only")
    z = args.zoom
    margin_l, margin_t, pad, title_h = 34, 12, 14, 14
    rw, rh = rect[2] * z, rect[3] * z
    total_h = len(panels) * (rh + margin_t + title_h + pad) + pad
    canvas = Image.new("RGBA", (rw + margin_l + 2 * pad, total_h), (24, 24, 30, 255))
    d = ImageDraw.Draw(canvas)
    y = pad
    for title, pal in panels:
        d.text((margin_l + pad, y), f"{name} {W}x{H}  {title}", fill=(230, 230, 240, 255))
        y += title_h
        for tx in range(rect[2] // 8):
            d.text((margin_l + pad + tx * 8 * z + 2, y), f"{(rect[0] // 8 + tx):X}", fill=(160, 160, 190, 255))
        y += margin_t
        panel = render(px, (W, H), rect, pal, z, not args.no_grid, used, not args.no_dim, tile_cols)
        for ty in range(rect[3] // 8):
            d.text((2, y + ty * 8 * z + 2), f"{((rect[1] // 8 + ty) * tile_cols + rect[0] // 8):03X}", fill=(160, 160, 190, 255))
        canvas.paste(panel, (margin_l + pad, y))
        y += rh + pad
        if pal is not png_pal:
            sw = 12
            for i, c in enumerate(pal[:16]):
                d.rectangle([margin_l + pad + i * (sw + 2), y - pad + 1, margin_l + pad + i * (sw + 2) + sw, y - 2], fill=(*c, 255))
    out = args.out or OUT_DIR / f"{name}.png"
    out.parent.mkdir(parents=True, exist_ok=True)
    canvas.convert("RGB").save(out)
    print(f"wrote {out.relative_to(ROOT) if out.is_relative_to(ROOT) else out}  ({canvas.width}x{canvas.height})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
